#pragma once

#include "core/byte_io.hpp"
#include "wasafe/model/hierarchy.hpp"

namespace WaSafe {

/// Сериализация иерархии дизайна вместе с системой типов.
///
/// Пишется только то, что не выводится: у scope — имя, вид и родитель, у узла
/// сигнала — имя, тип, scope, родитель, поток и проекция. Индексы имён, списки
/// детей и обратные ссылки восстанавливают сами методы добавления, а порядок
/// id совпадает автоматически: они раздаются по позиции в векторе.
///
/// Типы выносятся в отдельную таблицу с дедупликацией по адресу дескриптора:
/// граф типов реально разделяется (у массива один элементный тип на все
/// элементы), поэтому массив на тысячу элементов даёт одну запись.
void encodeHierarchy(ByteWriter& w, const Hierarchy& h);

/// Разбор того, что записал encodeHierarchy. Бросает Exception на повреждённом
/// или несогласованном потоке.
[[nodiscard]] Hierarchy decodeHierarchy(ByteReader& r);

}  // namespace WaSafe
